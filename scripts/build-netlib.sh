#!/bin/bash
# Builds Assets/Plugins/WebGL/BtgNet.jspre: the Poki Netlib (the "legacy" browser build of @poki/netlib, kept in scripts/net/vendor) followed by our
# small bridge (scripts/net/btg-net.js). Unity puts every .jspre in front of the WebGL framework, so `netlib` and `BTGNet` exist in the page without
# any change to the WebGL template and without downloading anything.
# To update Netlib: npm install @poki/netlib, copy node_modules/@poki/netlib/dist/legacy.js to scripts/net/vendor/ (and fix the name below), run this again.
set -e
cd "$(dirname "$0")/net"
OUT="../../Assets/Plugins/WebGL/BtgNet.jspre"
{
  echo "// GENERATED by scripts/build-netlib.sh - do not edit. Poki Netlib 0.0.20 (ISC license, see scripts/net/vendor/netlib-LICENSE) + our bridge."
  cat vendor/netlib-0.0.20.legacy.js | sed '/^\/\/# sourceMappingURL/d'
  echo
  cat btg-net.js
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
